<details class="more">
    <summary>Wat is euthanasie, en wat zegt de wet?</summary>
    <div class="more-body">
<p>In Nederland betekent euthanasie een zelfgekozen levenseinde met hulp van een arts. De arts dient via een infuus een middel toe (<em>levensbeëindiging op verzoek</em>), of u neemt zelf een middel in dat de arts u geeft (<em>hulp bij zelfdoding</em>). In beide gevallen moet u erom vragen en mag alleen een arts het uitvoeren. De regels staan in de Wet toetsing levensbeëindiging op verzoek en hulp bij zelfdoding.</p>
<h2>De zorgvuldigheidseisen voor de arts</h2>
<ol>
    <li>Uw verzoek is vrijwillig (zonder druk van buiten) en weloverwogen.</li>
    <li>Uw lijden is uitzichtloos en ondraaglijk. Alleen u kunt bepalen wat voor u ondraaglijk is, maar uw arts moet het kunnen begrijpen. De oorzaak moet medisch zijn, lichamelijk of psychiatrisch.</li>
    <li>De arts heeft u voorgelicht over uw situatie en uw vooruitzichten.</li>
    <li>U en uw arts zijn het erover eens dat er geen redelijke andere oplossing is. U bent niet verplicht een andere oplossing te kiezen, maar leg uw arts uit waarom niet.</li>
    <li>Er is minstens één andere, onafhankelijke arts geraadpleegd (meestal een SCEN-arts) die u heeft gezien.</li>
    <li>De arts voert het medisch zorgvuldig uit en blijft bij u tot u bent overleden.</li>
</ol>
<h2>Euthanasie is geen recht</h2>
<p>Uw arts is niet verplicht euthanasie te verlenen, ook niet als het volgens de wet kan. Wil uw arts het niet, dan hoort die u te helpen een andere arts te vinden. U kunt ook zelf terecht bij een andere huisarts, een specialist of het Expertisecentrum Euthanasie (expertisecentrumeuthanasie.nl).</p>
<h2>Waarom een schriftelijk verzoek?</h2>
<p>Zolang u zelf nog om euthanasie kunt vragen, is een schriftelijk verzoek niet nodig. Kunt u dat niet meer, dan is het wel nodig: het komt dan in de plaats van uw mondelinge verzoek. Bespreek het op tijd met uw arts, zodat die weet dat u er goed over heeft nagedacht.</p>
<p>Na afloop wordt elke euthanasie getoetst door een regionale toetsingscommissie, om te beoordelen of uw arts zorgvuldig heeft gehandeld.</p>
